#!/bin/sh
# The dispatcher's entry points: one per function PulseAudio's libpulse.so.0
# exports (its whole API, so every application linking it loads), each a jump
# through the table dispatch.c fills.
#
#   gen-trampolines.sh /usr/lib/libpulse.so.0 OUTDIR   -> trampolines.S, names.h
set -eu
real=$1; out=$2
mkdir -p "$out"
names=$(nm -D --defined-only "$real" | awk '$2 == "T" { sub(/@.*/, "", $3); print $3 }' | grep '^pa_' | sort -u)
[ -n "$names" ] || { echo "no functions in $real" >&2; exit 1; }
{
    echo "/* generated by gen-trampolines.sh from $real */"
    echo "	.text"
    i=0
    for n in $names; do
        printf '\t.p2align 4\n\t.globl %s\n\t.type %s, @function\n%s:\n\tendbr64\n\tjmp *jb_pa_table+%d(%%rip)\n\t.size %s, .-%s\n' \
            "$n" "$n" "$n" $((i * 8)) "$n" "$n"
        i=$((i + 1))
    done
    echo '	.section .note.GNU-stack,"",@progbits'
} >"$out/trampolines.S.tmp"
{
    echo "/* generated by gen-trampolines.sh from $real */"
    echo "#define JB_PA_COUNT $(echo "$names" | wc -l)"
    printf '#define JB_PA_NAMES'
    for n in $names; do printf ' \\\n\t"%s",' "$n"; done
    echo
} >"$out/names.h.tmp"
mv "$out/trampolines.S.tmp" "$out/trampolines.S"
mv "$out/names.h.tmp" "$out/names.h"
